-- Recrea el esquema completo en cada arranque (desarrollo).
DROP TABLE IF EXISTS TechnicianCommunication CASCADE;
DROP TABLE IF EXISTS Message CASCADE;
DROP TABLE IF EXISTS Contract CASCADE;
DROP TABLE IF EXISTS Negotiation CASCADE;
DROP TABLE IF EXISTS ParticipantList CASCADE;
DROP TABLE IF EXISTS Request CASCADE;
DROP TABLE IF EXISTS Activity CASCADE;
DROP TABLE IF EXISTS PapPati CASCADE;
DROP TABLE IF EXISTS OviUser CASCADE;
DROP TABLE IF EXISTS Trainer CASCADE;
DROP TABLE IF EXISTS Technician CASCADE;

CREATE TABLE Trainer (
    trainer_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(100) NOT NULL UNIQUE,
    name VARCHAR(50) NOT NULL,
    lastName VARCHAR(50) NOT NULL,
    occupation VARCHAR(100),
    phone VARCHAR(20),
    address VARCHAR(150)
);

CREATE TABLE Technician (
    technician_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    name VARCHAR(50) NOT NULL,
    lastName VARCHAR(50) NOT NULL
);

CREATE TABLE Activity (
    activity_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    date DATE NOT NULL,
    duration INT NOT NULL,
    location VARCHAR(150) NOT NULL,
    category VARCHAR(50) NOT NULL,
    description TEXT,
    trainer_id INT NOT NULL,

    FOREIGN KEY (trainer_id)
    REFERENCES Trainer(trainer_id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE
);

CREATE TABLE OviUser (
    oviuser_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    lastName VARCHAR(50) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    phone VARCHAR(20) NOT NULL,
    password VARCHAR(255) NOT NULL,
    province VARCHAR(50),
    town VARCHAR(50),
    pc VARCHAR(10),
    age INT,
    gender VARCHAR(10),
    status VARCHAR(20) NOT NULL,
    rejectionReason TEXT,
    lopdConsent BOOLEAN NOT NULL,

    CHECK(status IN ('PENDING','ACCEPTED','REJECTED')),
    CHECK (age >= 0)
);

CREATE TABLE PapPati (
    pappati_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    lastName VARCHAR(50) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    phone VARCHAR(20) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    province VARCHAR(50),
    town VARCHAR(50),
    pc VARCHAR(10),
    age INT,
    gender VARCHAR(10),
    cvUrl VARCHAR(255),
    training VARCHAR(100),
    experience VARCHAR(50),
    experienceType VARCHAR(50),
    status VARCHAR(20) NOT NULL,
    rejectionReason TEXT,

    CHECK(status IN ('PENDING','ACCEPTED','REJECTED')),
    CHECK (age >= 0)
);

CREATE TABLE ParticipantList (
    participantList_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attendance BOOLEAN NOT NULL,
    attendanceCertificateUrl VARCHAR(255),

    activity_id INT NOT NULL,
    oviuser_id INT,
    pappati_id INT,

    FOREIGN KEY (activity_id)
    REFERENCES Activity(activity_id)
    ON DELETE CASCADE
    ON UPDATE CASCADE,

    FOREIGN KEY (oviuser_id)
    REFERENCES OviUser(oviuser_id)
    ON DELETE CASCADE
    ON UPDATE CASCADE,

    FOREIGN KEY (pappati_id)
    REFERENCES PapPati(pappati_id)
    ON DELETE CASCADE
    ON UPDATE CASCADE,

    CHECK (oviuser_id IS NOT NULL OR pappati_id IS NOT NULL),
    CHECK (oviuser_id IS NULL OR pappati_id IS NULL)
);

CREATE TABLE Request (
    request_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description TEXT NOT NULL,
    training VARCHAR(100),
    startDate DATE NOT NULL,
    endDate DATE NOT NULL,
    availabilityDate DATE,
    experience INT,
    experienceType VARCHAR(50),
    preferredGender VARCHAR(10),
    preferredPc VARCHAR(10),
    preferredAge INT,
    status VARCHAR(20) NOT NULL,
    rejectionReason TEXT,

    oviuser_id INT NOT NULL,

    FOREIGN KEY (oviuser_id)
    REFERENCES OviUser(oviuser_id)
    ON DELETE CASCADE
    ON UPDATE CASCADE,

    CHECK(status IN (
        'IN_REVIEW',
        'APPROVED',
        'REJECTED',
        'CONTRACT_ACTIVE',
        'CONTRACT_FINISHED'
    )),
    CHECK (endDate >= startDate)
);

CREATE TABLE Negotiation (
    negotiation_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stateOfApproval VARCHAR(20) NOT NULL,

    request_id INT NOT NULL,
    pappati_id INT NOT NULL,

    FOREIGN KEY (request_id)
    REFERENCES Request(request_id)
    ON DELETE CASCADE
    ON UPDATE CASCADE,

    FOREIGN KEY (pappati_id)
    REFERENCES PapPati(pappati_id)
    ON DELETE CASCADE
    ON UPDATE CASCADE,

    CHECK(stateOfApproval IN (
        'PENDING',
        'ACCEPTED',
        'IN_PROGRESS',
        'REJECTED',
        'CANCELLED'
    ))
);

CREATE TABLE Contract (
    contract_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wage DECIMAL(8,2) NOT NULL,
    startDate DATE NOT NULL,
    endDate DATE NOT NULL,
    url VARCHAR(255) NOT NULL,
    negotiation_id INT UNIQUE,

    FOREIGN KEY (negotiation_id)
    REFERENCES Negotiation(negotiation_id)
    ON DELETE CASCADE
    ON UPDATE CASCADE,

    CHECK (wage > 0),
    CHECK (endDate >= startDate)
);

CREATE TABLE Message (
    messageId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    messageDateTime TIMESTAMP NOT NULL,
    sender VARCHAR(20) NOT NULL,
    receiver VARCHAR(20) NOT NULL,
    text VARCHAR(300) NOT NULL,

    negotiation_id INT NOT NULL,

    FOREIGN KEY (negotiation_id)
    REFERENCES Negotiation(negotiation_id)
    ON DELETE CASCADE
    ON UPDATE CASCADE
);

CREATE TABLE TechnicianCommunication (
    communication_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    communicationDateTime TIMESTAMP NOT NULL,
    senderRole VARCHAR(20) NOT NULL,
    senderId INT,
    recipientType VARCHAR(20) NOT NULL,
    recipientId INT NOT NULL,
    subject VARCHAR(120) NOT NULL,
    text TEXT NOT NULL,

    CHECK(senderRole IN ('TECNICO','OVIUSER','PAPPATI')),
    CHECK(recipientType IN ('OVIUSER','PAPPATI','TECNICO'))
);
